// Build-time helper: prints the numeric PiPL values for the flags in Ribbon3D_Flags.h,
// evaluated with the SDK's own enums. Usage: PiPLValuesGen <out.h>
#include <cstdio>

#include "AEConfig.h"
#include "AE_Effect.h"
#include "Ribbon3D_Flags.h"

int main(int argc, char** argv) {
    if (argc < 2) return 1;
    FILE* f = std::fopen(argv[1], "w");
    if (!f) return 2;
    std::fprintf(f, "/* Generated by tools/PiPLValuesGen.cpp - do not edit. */\n");
    std::fprintf(f, "#define RB_PIPL_VERSION %lu\n", (unsigned long)(RB_VERSION));
    std::fprintf(f, "#define RB_PIPL_OUTFLAGS %lu\n", (unsigned long)(RB_OUT_FLAGS));
    std::fprintf(f, "#define RB_PIPL_OUTFLAGS2 %lu\n", (unsigned long)(RB_OUT_FLAGS2));
    std::fclose(f);
    return 0;
}

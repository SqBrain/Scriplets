#!/usr/bin/env bash
# Regenerates src/kernel/RibbonKernelPTX.h (the CUDA kernel as PTX text) with clang.
# No CUDA toolkit needed. Run after changing src/kernel/*.h.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
clang="${CLANG:-clang++}"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
# sm_52 PTX is JIT-compiled by the driver for every newer NVIDIA GPU; PTX ISA 6.0 needs driver R410+.
"$clang" -x cuda --cuda-device-only -nocudainc -nocudalib --cuda-gpu-arch=sm_52 \
    -Xclang -target-feature -Xclang +ptx60 -O3 -ffp-contract=fast \
    -I "$here/src/kernel" -S -o "$tmp/ribbon.ptx" "$here/src/kernel/RibbonKernel_ptx.cu"
if grep -q "\.extern \.func" "$tmp/ribbon.ptx"; then
    echo "error: the PTX calls external functions (libdevice); use NVVM builtins in RibbonKernel.h" >&2
    exit 1
fi
out="$here/src/kernel/RibbonKernelPTX.h"
{
    echo "// Generated by tools/build_ptx.sh from src/kernel - do not edit."
    echo "#pragma once"
    echo "static const char kRibbonKernelPTX[] ="
    sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/    "/' -e 's/$/\\n"/' "$tmp/ribbon.ptx"
    echo "    ;"
} > "$out"
echo "wrote $out ($(wc -c < "$tmp/ribbon.ptx") bytes of PTX, $(grep -m1 '^\.version' "$tmp/ribbon.ptx"))"
